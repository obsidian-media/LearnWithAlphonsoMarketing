/**
 * Builds everything this site takes from the app, from the app's own source at ONE pinned commit
 * (design/app-source.json). Nothing the app owns is typed by hand on this site:
 *
 *   lib/app-facts.generated.ts            course, unit and lesson counts, levels, rooms, Practice content, leagues
 *   app/ds-tokens.generated.css           the app's design tokens (Royal palette, night via prefers-color-scheme)
 *                                         plus the site's larger type and spacing scale (design/site-scale.json)
 *   components/shared/icon-sprite.generated.ts   the app's icon set (design/icons/*.svg)
 *   public/fonts/*.woff                   Bricolage Grotesque and Figtree, the app's files
 *   public/art/rooms/<id>.webp            every painted room the unit room map uses
 *   public/art/alphonso.webp, hector.webp the realistic character renders
 *
 * Usage (needs a checkout of the public app repo at the pinned commit):
 *   bun scripts/sync-app.ts --app ../LearnWithAlphonso            write the files
 *   bun scripts/sync-app.ts --app ../LearnWithAlphonso --check    exit 1 if any written file would change
 *   bun scripts/sync-app.ts --app ../LearnWithAlphonso --pin      move the pin to the checkout's HEAD, then write
 *
 * CI runs --check against a fresh checkout of the pinned commit (.github/workflows/ci.yml), so a hand edit to
 * any generated file, or a pin moved without regenerating, fails the build.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const SITE = path.resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const appArg = args[args.indexOf("--app") + 1];
if (!args.includes("--app") || !appArg) {
  console.error(
    "usage: bun scripts/sync-app.ts --app <path to LearnWithAlphonso checkout> [--check | --pin]",
  );
  process.exit(2);
}
const APP = path.resolve(appArg);
const CHECK = args.includes("--check");
const PIN = args.includes("--pin");

const SOURCE_FILE = path.join(SITE, "design/app-source.json");
const source = JSON.parse(fs.readFileSync(SOURCE_FILE, "utf8")) as { repo: string; sha: string };
const head = execFileSync("git", ["-C", APP, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (PIN) {
  source.sha = head;
  fs.writeFileSync(SOURCE_FILE, JSON.stringify(source, null, 2) + "\n");
} else if (head !== source.sha) {
  console.error(
    `app checkout is at ${head}, the pin is ${source.sha}. Check out the pin, or pass --pin to move it.`,
  );
  process.exit(1);
}

const imp = (rel: string) => import(pathToFileURL(path.join(APP, rel)).href);
const read = (rel: string) => fs.readFileSync(path.join(APP, rel), "utf8");
const header = (comment: string) =>
  `${comment} Generated by scripts/sync-app.ts from ${source.repo}@${source.sha.slice(0, 12)}. Do not edit.`;

/* ---------------------------------------------------------------- facts */
const { COURSES, getCourse } = await imp("src/data/courses.ts");
const { LEVELS } = await imp("src/data/levels.ts");
const { ROOMS } = await imp("src/data/rooms.ts");
const { UNIT_ROOMS } = await imp("src/data/unit-rooms.ts");
const { SCENARIOS } = await imp("src/data/scenarios.ts");
const { CAMPAIGNS } = await imp("src/data/campaigns.ts");
const { LEAGUE_TIER_COPY } = await imp("src/lib/league-tier-copy.ts");
const tokens = JSON.parse(read("design/tokens.json"));

type U = { id: string; lessons: { questions: unknown[] }[] };
const courses = (COURSES as { id: string; label: string }[]).map((c) => {
  const units = (getCourse(c.id as never) as { curriculum: U[] }).curriculum;
  return {
    id: c.id,
    label: c.label,
    units: units.length,
    lessons: units.reduce((n, u) => n + u.lessons.length, 0),
    questions: units.reduce((n, u) => n + u.lessons.reduce((m, l) => m + l.questions.length, 0), 0),
  };
});
const roomIdsInUse = new Set(Object.values(UNIT_ROOMS as Record<string, string>));
const rooms = (ROOMS as { id: string; name: string }[])
  .filter((r) => roomIdsInUse.has(r.id))
  .map((r) => ({ id: r.id, name: r.name }));
if (rooms.length !== roomIdsInUse.size)
  throw new Error("the unit room map names a room that rooms.ts does not list");
const leagueColours = Object.keys(tokens.league).filter((k) => !k.startsWith("$"));
const leagues = Object.values(LEAGUE_TIER_COPY as Record<string, { label: string }>).map((t) => ({
  label: t.label,
  token: t.label.toLowerCase(),
}));
for (const l of leagues)
  if (!leagueColours.includes(l.token)) throw new Error(`no league colour token for ${l.label}`);

const picks = JSON.parse(fs.readFileSync(path.join(SITE, "design/app-picks.json"), "utf8"));
type Q = {
  id: string;
  type: string;
  prompt: string;
  choices?: string[];
  answer?: number;
  explanation?: string;
};
const demoCourse = (
  getCourse(picks.demoQuestion.course) as {
    curriculum: { level: string; lessons: { questions: Q[] }[] }[];
  }
).curriculum;
let demo: { level: string; q: Q } | null = null;
for (const u of demoCourse)
  for (const l of u.lessons)
    for (const q of l.questions) if (q.id === picks.demoQuestion.id) demo = { level: u.level, q };
if (!demo || demo.q.type !== "mc" || !demo.q.choices || demo.q.answer === undefined)
  throw new Error(
    `demo question ${picks.demoQuestion.id} is not a multiple-choice question in the app`,
  );
const scen = (
  SCENARIOS as { id: string; title: Record<string, string>; opener: Record<string, string> }[]
).find((s) => s.id === picks.heroScenario.id);
if (!scen) throw new Error(`scenario ${picks.heroScenario.id} is gone from the app`);
if (!rooms.some((r) => r.id === scen.id))
  throw new Error(`scenario ${scen.id} has no painted room`);

// The placement test: its longest run (the app's own picker, audio on) and the question types it draws from.
const placementRuns = (COURSES as { id: string }[]).map((c) => {
  const b = getCourse(c.id as never) as {
    placementPool: { type: string }[];
    pickPlacement: (audio?: boolean) => unknown[];
  };
  return {
    max: b.pickPlacement(true).length,
    types: [...new Set(b.placementPool.map((q) => q.type))].sort(),
  };
});
const placementMax = Math.max(...placementRuns.map((r) => r.max));
const placementTypes = [...new Set(placementRuns.flatMap((r) => r.types))].sort();

const facts = {
  source: { repo: source.repo, sha: source.sha },
  courses,
  totals: {
    courses: courses.length,
    units: courses.reduce((n, c) => n + c.units, 0),
    lessons: courses.reduce((n, c) => n + c.lessons, 0),
    questions: courses.reduce((n, c) => n + c.questions, 0),
  },
  levels: (LEVELS as { id: string }[]).map((l) => l.id),
  rooms,
  practice: {
    scenarios: (SCENARIOS as unknown[]).length,
    campaigns: (CAMPAIGNS as unknown[]).length,
  },
  leagues,
  placement: { maxQuestions: placementMax, questionTypes: placementTypes },
  demoQuestion: {
    id: demo.q.id,
    course: picks.demoQuestion.course,
    level: demo.level,
    prompt: demo.q.prompt,
    choices: demo.q.choices,
    answer: demo.q.answer,
    explanation: demo.q.explanation ?? "",
  },
  heroScenario: {
    id: scen.id,
    room: scen.id,
    title: scen.title[picks.heroScenario.course],
    opener: scen.opener[picks.heroScenario.course],
  },
};

const factsTs = `${header("//")}
// Every count and app fact the site shows comes from here. app/facts-guard.test.ts fails on a number typed
// next to these nouns anywhere else.

export const APP_FACTS = ${JSON.stringify(facts, null, 2)} as const;

export type CourseFact = (typeof APP_FACTS.courses)[number];
export type RoomFact = (typeof APP_FACTS.rooms)[number];
`;

/* ---------------------------------------------------------------- tokens */
// The app already renders design/tokens.json to CSS (scripts/export-design-system.ts, kept fresh by its
// design-system-sync test). Reuse that output rather than re-implement it: drop the Meadow palette (the site is
// Royal only) and follow the visitor's dark mode instead of the app's data-ds-mode switch.
/** Top-level CSS rules as [prelude, whole rule text]; comments between rules are dropped. */
function topLevelRules(src: string): { prelude: string; text: string }[] {
  const out: { prelude: string; text: string }[] = [];
  let i = 0;
  while (i < src.length) {
    if (src.startsWith("/*", i)) {
      i = src.indexOf("*/", i) + 2;
      continue;
    }
    if (/\s/.test(src[i]!)) {
      i++;
      continue;
    }
    const open = src.indexOf("{", i);
    if (open < 0) break;
    let depth = 0;
    let j = open;
    for (; j < src.length; j++) {
      if (src[j] === "{") depth++;
      else if (src[j] === "}" && --depth === 0) break;
    }
    out.push({ prelude: src.slice(i, open).trim(), text: src.slice(i, j + 1) });
    i = j + 1;
  }
  return out;
}
const NIGHT = ':root[data-ds-mode="night"]';
const kept: string[] = [];
for (const r of topLevelRules(read("src/styles/ds-tokens.generated.css"))) {
  if (r.prelude.includes('data-palette="meadow"')) continue;
  if (r.prelude.startsWith(NIGHT)) {
    const body = r.text.replace(NIGHT, ":root").replace(/\n/g, "\n  ");
    kept.push(`@media (prefers-color-scheme: dark) {\n  ${body}\n}`);
    continue;
  }
  if (r.prelude.includes("data-ds-mode")) throw new Error(`unhandled night selector: ${r.prelude}`);
  kept.push(r.text);
}
const scaleFile = tokens.marketing
  ? null
  : JSON.parse(fs.readFileSync(path.join(SITE, "design/site-scale.json"), "utf8"));
const scale = (tokens.marketing ?? scaleFile) as {
  type: Record<string, { min: number; fluid: number; max: number }>;
  layout: Record<string, number | { min: number; fluid: number; max: number }>;
};
const kebab = (s: string) => s.replace(/[A-Z0-9]+/g, (m) => "-" + m.toLowerCase());
const value = (v: number | { min: number; fluid: number; max: number }) =>
  typeof v === "number" ? `${v}px` : `clamp(${v.min}px, ${v.fluid}cqi, ${v.max}px)`;
const siteVars = [
  ...Object.entries(scale.type).map(([k, v]) => `  --site-${kebab(k)}: ${value(v)};`),
  ...Object.entries(scale.layout).map(([k, v]) => `  --site-${kebab(k)}: ${value(v)};`),
].join("\n");
const tokensCss = `${header("/*")} */
/* Royal palette only; night follows prefers-color-scheme. Site scale from ${
  tokens.marketing
    ? "design/tokens.json#marketing"
    : "design/site-scale.json (proposed for the app's tokens.json)"
}. */

${kept.join("\n").trim()}

:root {
${siteVars}
}
`;

/* ---------------------------------------------------------------- icons */
const iconDir = path.join(APP, "design/icons");
const symbols = fs
  .readdirSync(iconDir)
  .filter((f) => f.endsWith(".svg"))
  .sort()
  .map((f) => {
    const svg = fs.readFileSync(path.join(iconDir, f), "utf8").replace(/\r\n/g, "\n");
    const inner = svg
      .replace(/^[\s\S]*?<svg[^>]*>/, "")
      .replace(/<\/svg>\s*$/, "")
      .replace(/<title>[\s\S]*?<\/title>/, "")
      .replace(/fill="#000000"/g, 'fill="currentColor"')
      .replace(/\s*\n\s*/g, "")
      .trim();
    return { name: f.replace(/\.svg$/, ""), inner };
  });
const iconsTs = `${header("//")}

export const ICON_NAMES = ${JSON.stringify(symbols.map((s) => s.name))} as const;
export type IconName = (typeof ICON_NAMES)[number];

/** One <symbol id="i-NAME"> per app icon, drawn on a 24 grid with stroke="currentColor". */
export const ICON_SPRITE = ${JSON.stringify(
  symbols.map((s) => `<symbol id="i-${s.name}" viewBox="0 0 24 24">${s.inner}</symbol>`).join(""),
)};
`;

/* ---------------------------------------------------------------- write or check */
const text: Record<string, string> = {
  "lib/app-facts.generated.ts": factsTs,
  "app/ds-tokens.generated.css": tokensCss,
  "components/shared/icon-sprite.generated.ts": iconsTs,
};
const binary: Record<string, string> = {
  "public/art/alphonso.webp": "public/avatar/base.webp",
  "public/art/hector.webp": "public/hector/base.webp",
};
for (const f of fs.readdirSync(path.join(APP, "public/fonts")))
  binary[`public/fonts/${f}`] = `public/fonts/${f}`;
for (const r of rooms)
  binary[`public/art/rooms/${r.id}.webp`] = `public/avatar/scenes/${r.id}.webp`;

const stale: string[] = [];
for (const [rel, content] of Object.entries(text)) {
  const file = path.join(SITE, rel);
  const now = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (now === content) continue;
  if (CHECK) stale.push(rel);
  else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
for (const [rel, from] of Object.entries(binary)) {
  const file = path.join(SITE, rel);
  const want = fs.readFileSync(path.join(APP, from));
  if (fs.existsSync(file) && Buffer.compare(fs.readFileSync(file), want) === 0) continue;
  if (CHECK) stale.push(rel);
  else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, want);
  }
}
// Rooms that left the map must leave the site too.
const roomDir = path.join(SITE, "public/art/rooms");
if (fs.existsSync(roomDir))
  for (const f of fs.readdirSync(roomDir))
    if (!binary[`public/art/rooms/${f}`]) {
      if (CHECK) stale.push(`public/art/rooms/${f} (no longer in the room map)`);
      else fs.rmSync(path.join(roomDir, f));
    }

if (CHECK && stale.length) {
  console.error(
    `out of date with ${source.repo}@${source.sha}:\n  ${stale.join("\n  ")}\nRun: bun scripts/sync-app.ts --app <checkout>`,
  );
  process.exit(1);
}
console.log(
  `${CHECK ? "checked" : "wrote"} ${Object.keys(text).length + Object.keys(binary).length} files from ${source.sha.slice(0, 12)}: ` +
    `${facts.totals.units} units, ${facts.totals.lessons} lessons, ${rooms.length} rooms`,
);
